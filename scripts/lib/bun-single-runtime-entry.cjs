'use strict';

const { BOOTSTRAP_READER_SOURCE } = require('./bun-single-archive.cjs');
// One generated reader contract, shared verbatim with the Node producer.
const BOOTSTRAP_READER_LINES = BOOTSTRAP_READER_SOURCE.split('\n');

// Keep bootstrap generation testable without executing the package build.
function createSingleBinaryEntry(manifestSha, compressedManifest, stagedSpecifiers = {}) {
  return [
    'import crypto from \'node:crypto\';',
    'import fs from \'node:fs\';',
    'import os from \'node:os\';',
    'import path from \'node:path\';',
    'import zlib from \'node:zlib\';',
    'import Module from \'node:module\';',
    'import { pathToFileURL } from \'node:url\';',
    '',
    `const ARCHIVE_SHA256 = '${manifestSha}';`,
    `const MANIFEST_BASE64 = '${compressedManifest.toString('base64')}';`,
    '',
    'function resolveCacheRoot(): string {',
    '  const candidates = [',
    '    process.env.XPOD_BUN_SINGLE_CACHE_DIR,',
    '    path.join(os.tmpdir(), \'xpod-bun-cache\'),',
    '    path.join(os.homedir(), \'.xpod\', \'bun-single-cache\'),',
    '  ].filter((value): value is string => typeof value === \'string\' && value.length > 0);',
    '  for (const candidate of candidates) {',
    '    try {',
    '      const absolute = path.resolve(candidate);',
    '      fs.mkdirSync(absolute, { recursive: true });',
    '      return absolute;',
    '    } catch {',
    '    }',
    '  }',
    '  throw new Error(\'No writable cache directory found for Bun single binary.\');',
    '}',
    '',
    "",
    // Reader generated from scripts/lib/bun-single-archive.cjs at build time.
    // Hand-editing is impossible by construction: the shared codec is authoritative.
    ...BOOTSTRAP_READER_LINES,
  'function ensureExtracted(cacheDir: string): void {',
    '  const marker = path.join(cacheDir, \'.xpod-bun-single-ready\');',
    '  const entryPath = path.join(cacheDir, \'dist\', \'__cli__.cjs\');',
    '  try {',
    '    if (fs.readFileSync(marker, \'utf8\').trim() === ARCHIVE_SHA256 && fs.statSync(entryPath).isFile()) {',
    '      return;',
    '    }',
    '  } catch {',
    '  }',
    '  if (fs.existsSync(cacheDir)) {',
    '    fs.rmSync(cacheDir, { recursive: true, force: true });',
    '  }',
    '  fs.mkdirSync(cacheDir, { recursive: true });',
    '  const compressedManifest = Buffer.from(MANIFEST_BASE64, \'base64\');',
    '  const actualSha = crypto.createHash(\'sha256\').update(compressedManifest).digest(\'hex\');',
    '  if (actualSha !== ARCHIVE_SHA256) {',
    '    throw new Error(\'Embedded manifest checksum mismatch.\');',
    '  }',
    '  const archive = zlib.brotliDecompressSync(compressedManifest);',
    '  const entries = decodeArchive(archive);',
    '  for (const item of entries) {',
    '    const targetPath = path.join(cacheDir, item.path);',
    '    fs.mkdirSync(path.dirname(targetPath), { recursive: true });',
    '    fs.writeFileSync(targetPath, item.content);',
    '    if (process.platform !== \'win32\' && typeof item.mode === \'number\') {',
    '      fs.chmodSync(targetPath, item.mode);',
    '    }',
    '  }',
    '  fs.writeFileSync(marker, `${ARCHIVE_SHA256}\\n`);',
    '}',
    '',
    'async function main(): Promise<void> {',
    '  const cacheRoot = resolveCacheRoot();',
    '  const cacheDir = path.join(cacheRoot, ARCHIVE_SHA256.slice(0, 16));',
    '  ensureExtracted(cacheDir);',
    `  const stagedSpecifiers: Record<string, string> = ${JSON.stringify(stagedSpecifiers)};`,
    '  const originalRequire = Module.prototype.require;',
    // Resolve a declared public package the way Node would from the REQUESTING
    // module first. The map is only a ROOT fallback for compiled contexts whose
    // own resolution cannot see the staged tree (for example a bundle that no
    // longer lives beside node_modules). Never force a nested importer back to
    // the hoist copy just because the name appears in the map.',
    '  const directoryOf = (from: string | undefined): string | undefined => {',
    '    if (typeof from !== \'string\' || from.length === 0) return undefined;',
    '    try {',
    '      const stat = fs.statSync(from, { throwIfNoEntry: false });',
    '      return stat && stat.isFile() ? path.dirname(from) : from;',
    '    } catch {',
    '      return path.dirname(from);',
    '    }',
    '  };',
    '  // Only a resolution that lands INSIDE the staged tree may be used. Anything',
    '  // else (a host node_modules, an absolute escape) is refused, so a compiled',
    '  // run never loads unstaged product files.',
    '  const confinedToCache = (resolved: string | undefined): string | undefined => {',
    '    if (!resolved) return undefined;',
    '    const relative = path.relative(cacheDir, resolved);',
    '    if (relative.startsWith(\'..\') || path.isAbsolute(relative)) return undefined;',
    '    return resolved;',
    '  };',
    '  // Resolve a bare specifier the way Node does for the REQUESTING file, honouring',
    '  // the package exports gate. Filesystem scope is decided by walking ancestor',
    '  // node_modules from the requester; nothing here is a global name lookup.',
    '  //',
    '  // Bun compiled builds expose no resolver that enforces `exports` (measured:',
    '  // createRequire.resolve, Bun.resolveSync, import.meta.resolve and Module._findPath',
    '  // all return the private main for a package whose exports has no "."), so the',
    '  // gate is implemented here from the manifest itself.',
    '  const LEGACY_MISSING_EXPORT = \'ERR_PACKAGE_PATH_NOT_EXPORTED\';',
    '  const supportedConditions = (kind: string): string[] => kind === \'import\'',
    '    ? [\'import\', \'node\', \'default\']',
    '    : [\'require\', \'node\', \'default\'];',
    '  const pickExportedTarget = (value: unknown, kind: string): string | undefined => {',
    '    if (typeof value === \'string\') return value;',
    '    if (Array.isArray(value)) {',
    '      for (const item of value) {',
    '        const picked = pickExportedTarget(item, kind);',
    '        if (picked !== undefined) return picked;',
    '      }',
    '      return undefined;',
    '    }',
    '    if (value && typeof value === \'object\') {',
    '      // Declaration order decides, filtered by the conditions this requester',
    '      // actually provides; `default` is always available and is simply one of',
    '      // the keys, so an earlier matching key legitimately wins.',
    '      const allowed = supportedConditions(kind);',
    '      for (const key of Object.keys(value as Record<string, unknown>)) {',
    '        if (!allowed.includes(key)) continue;',
    '        const picked = pickExportedTarget((value as Record<string, unknown>)[key], kind);',
    '        if (picked !== undefined) return picked;',
    '      }',
    '    }',
    '    return undefined;',
    '  };',
    '  const exportMapFor = (exportsField: unknown): Record<string, unknown> | undefined => {',
    '    if (exportsField === null || exportsField === undefined) return undefined;',
    '    if (typeof exportsField === \'string\' || Array.isArray(exportsField)) return { \'.\': exportsField };',
    '    if (typeof exportsField !== \'object\') return undefined;',
    '    const record = exportsField as Record<string, unknown>;',
    '    const keys = Object.keys(record);',
    '    // An object mixing "." keys and condition keys is invalid in Node; treat any.',
    '    // "." key as the subpath map and otherwise as main sugar for ".".',
    '    return keys.some((key) => key === \'.\' || key.startsWith(\'./\')) ? record : { \'.\': record };',
    '  };',
    '  const exportedTargetFor = (map: Record<string, unknown>, subpath: string, kind: string): string | undefined => {',
    '    if (Object.hasOwn(map, subpath)) return pickExportedTarget(map[subpath], kind);',
    '    // Pattern selection keeps the ACTUAL matching key, never just its prefix:',
    '    // re-selecting by prefix alone can pick a longer sibling whose suffix never',
    '    // matched (for example "./x/*.json" for the request "./x/foo"). Node ranks',
    '    // by longest matching PREFIX, then longest matching SUFFIX (a more specific',
    '    // key), then by the longer key overall.',
    '    let bestKey: string | undefined;',
    '    let bestPrefixLength = -1;',
    '    let bestSuffixLength = -1;',
    '    let bestMatch: string | undefined;',
    '    for (const key of Object.keys(map)) {',
    '      const star = key.indexOf(\'*\');',
    '      if (star < 0) continue;',
    '      const prefix = key.slice(0, star);',
    '      const suffix = key.slice(star + 1);',
    '      if (subpath.length < prefix.length + suffix.length) continue;',
    '      if (!subpath.startsWith(prefix) || !subpath.endsWith(suffix)) continue;',
    '      const longerPrefix = prefix.length > bestPrefixLength;',
    '      const equalPrefixLongerSuffix = prefix.length === bestPrefixLength && suffix.length > bestSuffixLength;',
    '      const equalBothLongerKey = prefix.length === bestPrefixLength && suffix.length === bestSuffixLength',
    '        && (bestKey === undefined || key.length > bestKey.length);',
    '      if (bestKey === undefined || longerPrefix || equalPrefixLongerSuffix || equalBothLongerKey) {',
    '        bestKey = key;',
    '        bestPrefixLength = prefix.length;',
    '        bestSuffixLength = suffix.length;',
    '        bestMatch = subpath.slice(prefix.length, subpath.length - suffix.length);',
    '      }',
    '    }',
    '    if (bestKey === undefined || bestMatch === undefined) return undefined;',
    '    const target = pickExportedTarget(map[bestKey], kind);',
    '    return target === undefined ? undefined : target.replaceAll(\'*\', bestMatch);',
    '  };',
    '  const resolveInstalledRelative = (specifier: string, from: string | undefined, kind: string)',
    '    : { path: string } | { denied: string } | undefined => {',
    '    // Relative and absolute specifiers are NEVER package subpaths: they belong to',
    '    // the ordinary file resolver. Applying an exports gate to them broke real',
    '    // in-package requires such as drizzle-orm\'s \'../entity.cjs\'.',
    '    if (specifier.startsWith(\'.\') || path.isAbsolute(specifier)) return undefined;',
    '    const base = directoryOf(from);',
    '    if (!base) return undefined;',
    '    const segments = specifier.split(\'/\');',
    '    const packageName = specifier.startsWith(\'@\') ? segments.slice(0, 2).join(\'/\') : segments[0];',
    '    if (!packageName) return undefined;',
    '    const subpath = specifier === packageName ? \'.\' : \'./\' + specifier.slice(packageName.length + 1);',
    '    let directory = base;',
    '    for (;;) {',
    '      const candidate = path.join(directory, \'node_modules\', ...packageName.split(\'/\'));',
    '      const manifestPath = path.join(candidate, \'package.json\');',
    '      if (confinedToCache(manifestPath) && fs.existsSync(manifestPath)) {',
    '        const manifest = JSON.parse(fs.readFileSync(manifestPath, \'utf8\'));',
    '        const map = exportMapFor(manifest.exports);',
    '        let target: string | undefined;',
    '        if (map) {',
    '          target = exportedTargetFor(map, subpath, kind);',
    '          // A declared exports map is authoritative: an unlisted subpath is',
    '          // NOT allowed to fall back to main or to a private file.',
    '          if (target === undefined) return { denied: LEGACY_MISSING_EXPORT };',
    '        } else {',
    '          // No exports field (or explicit null): classic main/index resolution.',
    '          if (subpath === \'.\') {',
    '            target = typeof manifest.main === \'string\' && manifest.main.length > 0 ? manifest.main : \'index.js\';',
    '          } else {',
    '            target = subpath;',
    '          }',
    '        }',
    '        const file = path.resolve(candidate, target);',
    '        for (const attempt of [file, file + \'.js\', file + \'.cjs\', file + \'.mjs\', path.join(file, \'index.js\')]) {',
    '          if (fs.existsSync(attempt) && fs.statSync(attempt).isFile()) {',
    '            const confined = confinedToCache(attempt);',
    '            return confined ? { path: confined } : { denied: LEGACY_MISSING_EXPORT };',
    '          }',
    '        }',
    '        return { denied: LEGACY_MISSING_EXPORT };',
    '      }',
    '      const parent = path.dirname(directory);',
    '      if (parent === directory || !confinedToCache(directory)) return undefined;',
    '      directory = parent;',
    '    }',
    '  };',
    '  const declaredStagedPath = (specifier: string): string | undefined => {',
    '    return Object.hasOwn(stagedSpecifiers, specifier) ? path.join(cacheDir, stagedSpecifiers[specifier]) : undefined;',
    '  };',
    '  // Compiled Bun resolves bare specifiers through its own loader before this',
    '  // wrapper sees them, so a scoped JavaScript-level answer is not enough: the',
    '  // plugin below maps the request to an ABSOLUTE staged path. This wrapper',
    '  // remains for classic CJS callers that do reach Module.prototype.require.',
    '  // Requester-scoped first. A DENIED result (exports forbids the subpath) must',
    '  // propagate as the standard error; it must never be softened into a root or',
    '  // private-file fallback.',
    '  const deniedError = (specifier: string, code: string): never => {',
    '    const error = new Error(`Package subpath \'${specifier}\' is not defined by "exports" (${code})`);',
    '    (error as { code?: string }).code = code;',
    '    throw error;',
    '  };',
    '  Module.prototype.require = function(specifier: string) {',
    '    const scoped = resolveInstalledRelative(specifier, (this as { filename?: string }).filename, \'require\');',
    '    if (scoped && \'path\' in scoped) return originalRequire.call(this, scoped.path);',
    '    if (scoped && \'denied\' in scoped) return deniedError(specifier, scoped.denied);',
    '    // Only the compiled root map remains, for names the staged tree advertises.',
    '    const staged = declaredStagedPath(specifier);',
    '    if (staged) return originalRequire.call(this, staged);',
    '    return originalRequire.call(this, specifier);',
    '  };',
    '  Bun.plugin({ name: \'canonical-staged-public-packages\', setup(build) {',
    '    build.onResolve({ filter: /^[^./]/ }, args => {',
    '      // Bun supplies importer for ESM and resolveDir for CJS; both identify the',
    '      // same requesting context. Treat an EMPTY string as absent: `?? ` would',
    '      // keep "" and silently discard a valid resolveDir, which would lose the',
    '      // requester scope for exactly those callers.',
    '      const hookArgs = args as { importer?: string; resolveDir?: string };',
    '      const requester = hookArgs.importer !== undefined && hookArgs.importer.length > 0',
    '        ? hookArgs.importer',
    '        : hookArgs.resolveDir;',
    '      // Derive the requester kind from what Bun actually reports instead of',
    '      // assuming ESM. A CJS require reaching this hook must get require',
    '      // conditions; only genuine import contexts get import conditions.',
    '      const hookKind = (args as { kind?: string }).kind;',
    '      const requesterKind = hookKind === \'require-call\' || hookKind === \'require-resolve\'',
    '        ? \'require\'',
    '        : \'import\';',
    '      const scoped = resolveInstalledRelative(args.path, requester, requesterKind);',
    '      if (scoped && \'path\' in scoped) return { path: scoped.path };',
    '      if (scoped && \'denied\' in scoped) throw deniedError(args.path, scoped.denied);',
    '      const staged = declaredStagedPath(args.path);',
    '      return staged ? { path: staged } : undefined;',
    '    });',
    '  } });',
    '  const entryPath = path.join(cacheDir, \'dist\', \'__cli__.cjs\');',
    '  const argv0 = process.argv[0] ?? process.execPath;',
    '  const childEntrypointAtArgv1 = process.argv[1]?.startsWith(\'__internal-\') === true;',
    '  const userArgs = childEntrypointAtArgv1 ? process.argv.slice(1) : process.argv.slice(2);',
    '  process.argv = [argv0, entryPath, ...userArgs];',
    '  process.env.XPOD_BUN_SINGLE_RUNTIME = \'1\';',
    '  process.chdir(cacheDir);',
    '  await import(pathToFileURL(entryPath).href);',
    '}',
    '',
    'void main();',
    '',
  ].join('\n');
}

module.exports = { createSingleBinaryEntry };
