import time
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('prepared_probe_backend',ROOT/'qlever/scripts/sdk-ptrace-execution.py');backend=importlib.util.module_from_spec(spec);spec.loader.exec_module(backend)

def identity(path):
    data=path.read_bytes();item=path.stat()
    return dict(path=str(path),identity=backend.probe.identity(item),bytes=len(data),sha256=hashlib.sha256(data).hexdigest())
class OldLifecycle(backend.Observer):
    def seal_prepared_build_inputs(self):self.prepared_sealed=True
class ChangedPrepared(backend.Observer):
    def seal_prepared_build_inputs(self):
        super().seal_prepared_build_inputs()
        self.changed_path.write_bytes(b'prepared-18\n')

def close_actual(observer,path):
    waits=[];known=set(observer.tasks)
    with path.open('xb') as raw:
        def emit(row):
            data=(json.dumps(row,sort_keys=True)+'\n').encode();assert raw.tell()+len(data)<=4*1024**2;raw.write(data);raw.flush();os.fsync(raw.fileno())
        emit(dict(kind='cleanup-start',knownTrackedPids=sorted(known)));observer.abort()
        with backend.owned_wait.BlockingOwnedWait(time.monotonic()+5,backend.WALL) as waiter:
            while True:
                try:
                    pid,status=waiter.wait_one();waits.append(dict(pid=pid,status=status));emit(dict(kind='actual-cleanup-wait',pid=pid,status=status))
                    assert pid in known,'cleanup wait returned an unregistered PID'
                    if os.WIFSTOPPED(status):
                        # SIGKILL can still produce PTRACE_EVENT_EXIT. Killing
                        # again never resumes that stop; actual CONT is needed
                        # before a final exit/signal wait and kernel ECHILD.
                        try:backend.single.trace(7,pid,0,9);emit(dict(kind='actual-cleanup-ptrace-cont',pid=pid,signal=9,event=status>>16))
                        except ProcessLookupError:emit(dict(kind='actual-cleanup-ptrace-cont-esrch',pid=pid))
                    else:assert os.WIFEXITED(status) or os.WIFSIGNALED(status),'unexpected actual cleanup status'
                except ChildProcessError:
                    emit(dict(kind='actual-cleanup-echild'));return dict(actualEchild=True,waits=waits)

def run(out):
    out=Path(out);out.mkdir(parents=True,exist_ok=False);results={}
    for name,kind in [('old-lifecycle',OldLifecycle),('prepared-positive',backend.Observer),('prepared-changed',ChangedPrepared)]:
        case=out/name;case.mkdir();build=case/'build';build.mkdir();originals=case/'originals';originals.mkdir()
        marker=build/'.xpod-source-prepared';other=build/'arbitrary-preexisting.conf'
        marker.write_bytes(b'prepared-17\n');other.write_bytes(b'other-input\n');before=[identity(marker),identity(other)]
        observer=kind(originals,ROOT,build,deadline_monotonic=time.monotonic()+20,maximum_bytes=32*1024**2,maximum_file_bytes=1024**2,selected_names=None);observer.changed_path=marker
        command=['bash','-c','cat "$1" "$2"','prepared-input-probe',str(marker),str(other)]
        result={}
        try:
            phase=observer.phase('configure',command,cwd=str(ROOT),env={'PATH':'/usr/bin:/bin','LANG':'C','LC_ALL':'C'})
            lines=[(originals/'configure.syscalls.original.jsonl').read_bytes().splitlines(keepends=True)]
            report=backend.bindings.observe([('configure',lines[0])],lambda name,maximum:(originals/name).read_bytes(),{})
            assert phase['trackingReceipt']['actualRootReturnCode']==0 and phase['trackingReceipt']['trackedProcessesClosed'] is True
            assert name=='prepared-positive' and report['preparedInputConsumerBytesVerified'] and len(report['preparedInputConsumers'])==2 and report['outputs']==[]
            result=dict(actualReturnCode=0,tracking=phase['trackingReceipt'],preparedInputConsumerBytesVerified=True,generatedOutputs=report['outputs'],preparedConsumers=report['preparedInputConsumers'])
        except BaseException as error:
            message=str(error);result=dict(errorType=type(error).__name__,error=message)
            if name=='old-lifecycle':assert 'lacks actual producer or sealed prepared FD' in message
            elif name=='prepared-changed':assert 'actual prepared/generated bytes changed' in message
            else:raise
        finally:
            (case/'before-cleanup.observation.json').write_text(json.dumps(result,indent=2)+'\n')
            result['cleanup']=close_actual(observer,case/'cleanup.wait.original.jsonl')
        result.update(before=before,after=[identity(marker),identity(other)])
        if name=='prepared-changed':assert result['before'][0]['identity'][:2]==result['after'][0]['identity'][:2] and result['before'][0]['sha256']!=result['after'][0]['sha256']
        (case/'observation.json').write_text(json.dumps(result,indent=2)+'\n');results[name]=result
    summary=dict(scope='same observer prepared-input byte lifecycle only; no SDK/source qualification',oldLifecycleRejected=True,actualPreparedConsumerBytesVerified=True,actualSameInodeChangedBytesRejected=True,overallSdkSourceVerified=False,cases=results)
    (out/'observation.json').write_text(json.dumps(summary,indent=2)+'\n');print(json.dumps({key:value for key,value in summary.items() if key!='cases'}))
if __name__=='__main__':
    assert len(sys.argv)==2;run(sys.argv[1])
